"""Generate the complete source listing/tree/checksums, or check them in CI.

Usage: python scripts/package_project.py [--check]
The delivered ZIP is assembled separately so signing credentials never enter
this project. Source and verification files, including this generator, are
covered by the resulting checksums.
"""
import argparse
import base64
import hashlib
from pathlib import Path

root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser()
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
generated={'FULL_SOURCE.md','PROJECT_TREE.txt','SHA256SUMS.txt'}
def files():
    # Exclude private signing material and machine state from the public source listing.
    return sorted(p for p in root.rglob('*') if p.is_file() and
        not set(p.relative_to(root).parts)&{'.git','.venv','venv','build','build-before-audit','.gradle','.idea','.kotlin','__pycache__'} and
        p.name!='local.properties' and p.suffix not in {'.apk','.aab','.jks','.keystore','.pyc'})
def checksum(path):
    # Hash exact bytes so unrecorded source or line-ending changes fail the packaging gate.
    return hashlib.sha256(path.read_bytes()).hexdigest()
if args.check:
    lines=(root/'SHA256SUMS.txt').read_text().splitlines()
    known={name:digest for digest,name in (line.split('  ',1) for line in lines)}
    actual={str(p.relative_to(root)):checksum(p) for p in files() if p.name!='SHA256SUMS.txt'}
    assert known==actual,'Source files/listings/checksums changed; run scripts/package_project.py again.'
    print('PASS: complete source/listing checksums match.')
else:
    source=[p for p in files() if p.name not in generated]
    names=sorted([str(p.relative_to(root)) for p in source]+list(generated))
    (root/'PROJECT_TREE.txt').write_text('Electro/\n'+''.join('  '+n+'\n' for n in names))
    listing=['# Electro — complete project source\n\nGenerated by scripts/package_project.py. Edit source files, then regenerate.\n\n']
    for p in source:
        name=str(p.relative_to(root))
        if p.suffix.lower() in {'.png','.webp','.jpg','.jpeg'}:
            listing.append(f'## {name}\n\nBinary image asset; see this path and SHA256SUMS.txt for its exact bytes/hash.\n\n')
            continue
        try:
            content=p.read_text()
            language={'.kt':'kotlin','.kts':'kotlin','.xml':'xml','.json':'json','.py':'python','.yml':'yaml','.md':'markdown'}.get(p.suffix,'text')
        except UnicodeDecodeError:
            content=base64.b64encode(p.read_bytes()).decode()+'\n'
            language='text'
            name+=' (Base64)'
        fence='`'*max(4,max((len(x) for x in __import__('re').findall('`+',content)),default=0)+1)
        listing.append(f'## {name}\n\n{fence}{language}\n{content}\n{fence}\n\n')
    (root/'FULL_SOURCE.md').write_text(''.join(listing))
    (root/'SHA256SUMS.txt').write_text(''.join(checksum(p)+'  '+str(p.relative_to(root))+'\n' for p in files() if p.name!='SHA256SUMS.txt'))
    print(f'Generated listing, tree and checksums for {len(names)} files.')
